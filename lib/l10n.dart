        'Mind Stock v0.2.4\nYour daily life becomes an asset, just by recording.',
  };

  String tr(String key, {Map<String, String> args = const {}}) {
    final dict = isEn ? _en : _ja;
    var value = dict[key] ?? _ja[key] ?? key;
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

  String timeframeLabel(Timeframe tf) {
    return switch (tf) {
      Timeframe.daily => tr(isEn ? 'timeframe_day_long' : 'timeframe_day'),
      Timeframe.weekly => tr(isEn ? 'timeframe_week_long' : 'timeframe_week'),
      Timeframe.monthly => tr(
        isEn ? 'timeframe_month_long' : 'timeframe_month',
      ),
    };
  }

  String timeframeLabelShort(Timeframe tf) {
    return switch (tf) {
      Timeframe.daily => tr('timeframe_day'),
      Timeframe.weekly => tr('timeframe_week'),
      Timeframe.monthly => tr('timeframe_month'),
    };
  }

  String eventKindLabel(EventKind kind) {
    return switch (kind) {
      EventKind.daily => tr('event_kind_daily'),
      EventKind.mood => tr('event_kind_mood'),
      EventKind.milestone => tr('event_kind_milestone'),
    };
  }

  String date(
    DateTime date, {
    required String jaPattern,
    required String enPattern,
  }) {
    final pattern = isEn ? enPattern : jaPattern;
    final locale = isEn ? 'en_US' : 'ja_JP';
    return DateFormat(pattern, locale).format(date);
  }
}

